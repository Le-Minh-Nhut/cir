def plan(env: dict, command: list[str], *, checkpoint_sha: str | None = None,
         protocol: str = "fashioniq_original_split") -> em.EvaluationPlan:
    return em.EvaluationPlan(
        model_id=MODEL,
        checkpoint_id="ckpt_v1",
        protocol=protocol,
        dataset_root=env["tmp"] / "FashionIQ",
        source=env["source"],
        checkpoint=env["checkpoint"],
        cwd=env["source"],
        command=command,
        pin=PIN,
        actual_source_commit=PIN,
        paper_metrics=None,
    )


def reporting_script(tmp_path: Path, *, exit_code: int = 0, mutate=None) -> list[str]:
    """A tiny official-style evaluator that prints metrics and exits."""
    lines = [
        "import json, os, sys",
        'print("evaluating")',
        "print(json.dumps({"
        '"average_recall_at10": 55.0, "average_recall_at50": 75.0, "average_recall": 65.0,'
        '"dress_recall_at10": 60.0, "dress_recall_at50": 80.0,'
        '"shirt_recall_at10": 55.0, "shirt_recall_at50": 75.0,'
        '"toptee_recall_at10": 50.0, "toptee_recall_at50": 70.0}))',
    ]
    if mutate is not None:
        lines.insert(2, mutate)
    lines.append(f"sys.exit({exit_code})")
    script = tmp_path / f"evaluator_{uuid.uuid4().hex[:6]}.py"
    script.write_text("\n".join(lines) + "\n")
    return [sys.executable, str(script)]


def silent_script(tmp_path: Path) -> list[str]:
    """Exits 0 and writes absolutely nothing: no report, no output at all."""
    script = tmp_path / f"silent_{uuid.uuid4().hex[:6]}.py"
    script.write_text("import sys\nsys.exit(0)\n")
    return [sys.executable, str(script)]


def reports_of(env: dict) -> Path:
    return env["repo"] / "workbench" / "artifacts" / "reports"


def run(env: dict, command: list[str]) -> tuple[int, str]:
    run_id = f"{uuid.uuid4().hex[:12]}"
    code = em.execute(plan(env, command), env["config"], run_id=run_id)
    return code, run_id


