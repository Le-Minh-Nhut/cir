def test_out11_out12_failed_run_preserves_previous_success_and_reports_byte_identical(env):
    ok_code, ok_run = run(env, reporting_script(env["tmp"]))
    assert ok_code == 0
    successful = reports_of(env) / "csmcir_ckpt_v1_latest_successful.json"
    attempt = reports_of(env) / "csmcir_ckpt_v1_latest_attempt.json"
    assert json.loads(successful.read_text())["run_id"] == ok_run

    run_report = reports_of(env) / f"csmcir_ckpt_v1_{ok_run}_aggregate.json"
    proof = reports_of(env) / f"csmcir_ckpt_v1_{ok_run}_completion.json"
    before = (sha256_file(run_report), sha256_file(proof))

    fail_code, fail_run = run(env, reporting_script(env["tmp"], exit_code=3))
    assert fail_code == 3
    assert fail_run != ok_run

    # A failed run advances only latest_attempt.
    assert json.loads(successful.read_text())["run_id"] == ok_run, "failed run replaced latest_successful"
    assert json.loads(attempt.read_text())["run_id"] == fail_run
    assert json.loads(attempt.read_text())["return_code"] == 3
    # Previous artifacts remain byte-identical.
    assert (sha256_file(run_report), sha256_file(proof)) == before


