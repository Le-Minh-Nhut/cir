# --------------------------------------------------------------- OUT-11..OUT-13

def test_out11_out12_failed_run_preserves_previous_success_and_reports_byte_identical(env):
    ok_code, ok_run = run(env, reporting_script(env["tmp"]))
    assert ok_code == 0
    successful = reports_of(env) / "csmcir_ckpt_v1_latest_successful.json"
    attempt = reports_of(env) / "csmcir_ckpt_v1_latest_attempt.json"
    assert json.loads(successful.read_text())["run_id"] == ok_run

    run_report = reports_of(env) / f"csmcir_ckpt_v1_{ok_run}_aggregate.json"
    proof = reports_of(env) / f"csmcir_ckpt_v1_{ok_run}_completion.json"
    before = (sha256_file(run_report), sha256_file(proof))

    fail_code, fail_run = run(env, reporting_script(env["tmp"], exit_code=3))
    assert fail_code == 3
    assert fail_run != ok_run

    # A failed run advances only latest_attempt.
    assert json.loads(successful.read_text())["run_id"] == ok_run, "failed run replaced latest_successful"
    assert json.loads(attempt.read_text())["run_id"] == fail_run
    assert json.loads(attempt.read_text())["return_code"] == 3
    # Previous artifacts remain byte-identical.
    assert (sha256_file(run_report), sha256_file(proof)) == before


def test_out12b_successful_run_advances_latest_successful_and_preserves_history(env):
    first_code, first_run = run(env, reporting_script(env["tmp"]))
    assert first_code == 0
    second_code, second_run = run(env, reporting_script(env["tmp"]))
    assert second_code == 0

    successful = reports_of(env) / "csmcir_ckpt_v1_latest_successful.json"
    assert json.loads(successful.read_text())["run_id"] == second_run
    assert (reports_of(env) / f"csmcir_ckpt_v1_{first_run}_aggregate.json").is_file(), \
        "an earlier successful experiment must remain available"
    assert (reports_of(env) / f"csmcir_ckpt_v1_{first_run}_completion.json").is_file()


def test_out13_refuses_to_overwrite_an_existing_run_artifact(env):
    """Atomicity: an existing run-scoped artifact is never overwritten."""
    run_id = "fixed-run-identity"
    command = reporting_script(env["tmp"])
    assert em.execute(plan(env, command), env["config"], run_id=run_id) == 0

    run_report = reports_of(env) / f"csmcir_ckpt_v1_{run_id}_aggregate.json"
    digest_before = sha256_file(run_report)
    with pytest.raises(RuntimeError, match="refusing to overwrite"):
        em.execute(plan(env, command), env["config"], run_id=run_id)
    assert sha256_file(run_report) == digest_before


def test_out13b_interrupted_pointer_update_leaves_previous_success_intact(env, monkeypatch):
    first_code, first_run = run(env, reporting_script(env["tmp"]))
    assert first_code == 0
    successful = reports_of(env) / "csmcir_ckpt_v1_latest_successful.json"
    baseline = successful.read_text()

    original_replace = Path.replace

    def failing_replace(self, target):
        if str(target).endswith("_latest_successful.json"):
            raise OSError("simulated crash during pointer update")
        return original_replace(self, target)

    monkeypatch.setattr(Path, "replace", failing_replace)
    with pytest.raises(OSError):
        run(env, reporting_script(env["tmp"]))
    monkeypatch.undo()

    assert successful.read_text() == baseline, "the previous success pointer must survive a crash"
    assert not list(reports_of(env).glob("*latest_successful.json.tmp*"))


