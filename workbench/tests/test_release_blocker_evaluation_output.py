def test_out02_exit_zero_without_output_fails(env):
    code, run_id = run(env, silent_script(env["tmp"]))
    assert code == 0, "the evaluator's own exit code is reported unchanged"
    assert not (reports_of(env) / f"csmcir_ckpt_v1_{run_id}_completion.json").exists()
