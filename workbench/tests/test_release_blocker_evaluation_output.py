def test_out13b_interrupted_pointer_update_leaves_previous_success_intact(env, monkeypatch):
    first_code, first_run = run(env, reporting_script(env["tmp"]))
    assert first_code == 0
    successful = reports_of(env) / "csmcir_ckpt_v1_latest_successful.json"
    baseline = successful.read_text()

    original_replace = Path.replace

    def failing_replace(self, target):
        if str(target).endswith("_latest_successful.json"):
            raise OSError("simulated crash during pointer update")
        return original_replace(self, target)

    monkeypatch.setattr(Path, "replace", failing_replace)
    with pytest.raises(OSError):
        run(env, reporting_script(env["tmp"]))
    monkeypatch.undo()

    assert successful.read_text() == baseline, "the previous success pointer must survive a crash"
    assert not list(reports_of(env).glob("*latest_successful.json.tmp*"))


