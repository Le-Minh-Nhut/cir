"""Release-blocker regression tests: evaluation output identity and immutability.

OUT-01..OUT-14.

The whole point: a successful evaluation stage must be backed by a completion
proof generated by the *current* invocation. A leftover report, an old latest
pointer, or a merely-newer timestamp is never sufficient.
"""
