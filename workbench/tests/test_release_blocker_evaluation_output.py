def test_out08_mismatched_checkpoint_digest_and_report_digest_rejected(env):
    code, run_id = run(env, reporting_script(env["tmp"]))
    assert code == 0
    proof = reports_of(env) / f"csmcir_ckpt_v1_{run_id}_completion.json"

    payload = json.loads(proof.read_text())
    payload["report_digest"] = "0" * 64
    proof.write_text(json.dumps(payload))
    evidence = em.completion_validator(MODEL, "ckpt_v1", "fashioniq_original_split",
                                       PIN, env["config"])
    ok, reason, _ = evidence({"run_id": run_id})
    assert ok is False and "digest" in reason

    # A proof recording a different checkpoint digest than the selected checkpoint is
    # rejected as well (the checkpoint identity is part of the completion contract).
    code2, run_id2 = run(env, reporting_script(env["tmp"]))
    assert code2 == 0
    proof2 = reports_of(env) / f"csmcir_ckpt_v1_{run_id2}_completion.json"
    payload2 = json.loads(proof2.read_text())
    payload2["checkpoint_sha256"] = "e" * 64
    proof2.write_text(json.dumps(payload2))
    with pytest.raises(em.EvaluationOutputError, match="checkpoint digest"):
        em.validate_run_manifest(
            plan(env, reporting_script(env["tmp"])),
            proof2,
            run_id=run_id2,
            output_root=env["repo"] / "workbench" / "artifacts",
        )


