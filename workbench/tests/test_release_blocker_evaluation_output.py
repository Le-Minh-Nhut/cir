def test_out14_resume_does_not_skip_a_failed_or_incomplete_run(env):
    import workbench.scripts.pipeline as pipeline

    evidence = em.completion_validator(MODEL, "ckpt_v1", "fashioniq_original_split",
                                       PIN, env["config"])
    state = env["tmp"] / "state.json"
    stage = pipeline.Stage(
        name="evaluation",
        commands=(reporting_script(env["tmp"]),),
        model_id=MODEL,
        checkpoint_id="ckpt_v1",
        protocol="fashioniq_original_split",
        run_id="prior-run",
        evidence=evidence,
    )
    # A recorded COMPLETE that has no valid proof must be re-executed, not skipped.
    stage_id = pipeline.stage_key(stage)
    assert stage_id == f"evaluation:{MODEL}:ckpt_v1:fashioniq_original_split"
    pipeline.save_pipeline_state({"stages": {stage_id: {
        "stage_id": stage_id,
        "name": "evaluation", "model_id": MODEL, "status": "COMPLETE",
        "fingerprint": pipeline.compute_stage_input_fingerprint(stage, env["config"]),
        "run_id": "prior-run",
    }}}, state)

    launched: list[list[str]] = []
    import workbench.scripts.pipeline as pl

    monkeypatch_target = pl
    original = monkeypatch_target.run_command
    monkeypatch_target.run_command = lambda argv: launched.append(argv) or 0
    try:
        rc = pl.run_stages([stage], dry_run=False, resume=True, state_path=state, config=env["config"])
    finally:
        monkeypatch_target.run_command = original

    assert rc == 1, "a stage with no valid completion proof must not be treated as complete"
    # The decisive evidence: the recorded COMPLETE row with a matching fingerprint and
    # an absent proof did NOT cause a skip; the evaluator was launched with this
    # stage's own invocation run id.
    assert launched, "the stale COMPLETE record must not skip execution"
    # The stale row is replaced by the current invocation's real outcome, which is
    # FAILED here: the run produced no proof for the current run id.
    recorded = pipeline.load_pipeline_state(state)["stages"][stage_id]
    assert recorded["status"] == "FAILED", recorded["status"]


